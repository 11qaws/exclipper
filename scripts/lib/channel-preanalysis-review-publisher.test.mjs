test("the catalog snapshot verifier accepts the full review closure and rejects changed review bytes", async (t) => {
  const fixture = await createFixture(t);
  const reviewInputManifest = {
    ...fixture.manifest,
    videos: fixture.manifest.videos.map((video) => ({
      ...video,
      artifactIds: video.artifactIds.filter((artifactId) =>
        artifactId.startsWith("youtube-caption-bundle:") ||
        artifactId.startsWith("youtube-storyboard-visual-fingerprint:"),
      ),
    })),
    artifacts: fixture.manifest.artifacts.filter(
      ({ kind }) => kind === "transcript" || kind === "fingerprint",
    ),
  };
  await writeFile(
    join(fixture.catalogDir, "catalog.json"),
    serialize(reviewInputManifest),
  );
  const result = await publishChannelPreanalysisReview(
    publishInput(fixture),
    {
      prepareReview: ({ artifactRevision }) =>
        verifiedEmptyReview(fixture.contextBundle, artifactRevision),
      nowIso: () => COMMIT_AT,
    },
  );
  const verified = await verifyPersistedChannelCatalogSnapshot(
    fixture.catalogDir,
    AMORETTO_CHANNEL_PREANALYSIS_SOURCE,
  );
  assert.equal(verified.videos[0].state, "review-ready");

  const reviewPath = localArtifactPath(
    fixture.catalogDir,
    result.artifact.storageKey,
  );
  const changed = await readFile(reviewPath);
  changed[changed.byteLength - 2] ^= 1;
  await writeFile(reviewPath, changed);
  await assert.rejects(
    verifyPersistedChannelCatalogSnapshot(
      fixture.catalogDir,
      AMORETTO_CHANNEL_PREANALYSIS_SOURCE,
    ),
    (error) =>
      error.code === "ARTIFACT_DIGEST_MISMATCH" ||
      error.code === "REVIEW_ARTIFACT_INVALID",
  );
});
