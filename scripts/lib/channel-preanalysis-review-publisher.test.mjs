async function verifiedEmptyReview(
  contextBundle,
  revision,
  pipelineRevision = "scheduled-review-test-v1",
) {
  const source = {
    sourceId: AMORETTO_CHANNEL_PREANALYSIS_SOURCE.sourceId,
    channelId: AMORETTO_CHANNEL_PREANALYSIS_SOURCE.channelId,
    videoId: VIDEO_ID,
  };
  const participantGrounding = createBroadcastParticipantGrounding({
    sourceDurationMs: DURATION_MS,
    castRosterId: null,
    chapters,
  }, {
    visualIdentity: {
      receipt: { adapter: "visual-identity", revision: "test-visual-v1", status: "completed", inputCount: 0, processedCount: 0, unavailableReason: null },
      evidence: [],
    },
    voiceIdentity: {
      receipt: { adapter: "voice-identity", revision: "test-voice-v1", status: "completed", inputCount: 0, processedCount: 0, unavailableReason: null },
      evidence: [],
    },
  });
  const visualCoverage = createChannelPreanalysisVisualCoverageReceipt({
    sourceDurationMs: DURATION_MS,
    videoId: VIDEO_ID,
    sourceFingerprintDigest: sha256(
      Buffer.from(VISUAL_FINGERPRINT_TEXT, "utf8"),
    ),
    visualSeedTimestampsMs: [],
  });
  const digests = await createChannelPreanalysisReviewContentDigests({
    source,
    broadcastContext: contextBundle.broadcastContext,
    visualCoverage,
    participantGrounding,
    candidates: [],
  });
  const bundle = validateChannelPreanalysisReviewBundle({
    schemaVersion: CHANNEL_PREANALYSIS_REVIEW_BUNDLE_SCHEMA_VERSION,
    artifactId: channelPreanalysisReviewBundleArtifactId(VIDEO_ID, revision),
    artifactRevision: revision,
    createdAt: REVIEW_AT,
    source,
    sourceDurationMs: DURATION_MS,
    transcriptDigest: contextBundle.transcriptDigest,
    broadcastContext: contextBundle.broadcastContext,
    broadcastContextDigest: digests.broadcastContextDigest,
    visualCoverage,
    participantGrounding,
    participantGroundingProvenance: {
      schemaVersion: CHANNEL_PREANALYSIS_PARTICIPANT_PROVENANCE_SCHEMA_VERSION,
      checkpointDigest: digests.participantGroundingDigest,
      generatedAt: REVIEW_AT,
      pipelineRevision,
    },
    candidates: [],
    certificate: {
      schemaVersion: CHANNEL_PREANALYSIS_REVIEW_CERTIFICATE_SCHEMA_VERSION,
      pipelineRevision,
      outcome: "verified-empty",
      sourceIdentityDigest: digests.sourceIdentityDigest,
      transcriptDigest: contextBundle.transcriptDigest,
      broadcastContextDigest: digests.broadcastContextDigest,
      participantGroundingDigest: digests.participantGroundingDigest,
      visualCoverageDigest: digests.visualCoverageDigest,
      candidateSetDigest: digests.candidateSetDigest,
      finalCandidateIds: [],
    },
  });
  await verifyChannelPreanalysisReviewBundleIntegrity(bundle);
  return bundle;
}

function localArtifactPath(catalogDir, storageKey) {
  const prefix = `${AMORETTO_CHANNEL_PREANALYSIS_SOURCE.sourceId}/`;
  assert.equal(storageKey.startsWith(prefix), true);
  return join(catalogDir, storageKey.slice(prefix.length));
}

async function writeStorage(catalogDir, storageKey, bytes) {
  const path = localArtifactPath(catalogDir, storageKey);
  await mkdir(dirname(path), { recursive: true });
  await writeFile(path, bytes);
  return path;
}

async function createFixture(t) {
  const catalogDir = await mkdtemp(join(tmpdir(), "exclipper-review-publisher-"));
  t.after(() => rm(catalogDir, { force: true, recursive: true }));
  const contextBundle = await createContextBundle();
  const contextText = serialize(contextBundle);
  const contextBytes = Buffer.from(contextText, "utf8");
  const contextStorageKey =
    `${AMORETTO_CHANNEL_PREANALYSIS_SOURCE.sourceId}/videos/${VIDEO_ID}.v1.json`;
  const contextArtifact = {
    artifactId: `youtube-caption-bundle:${VIDEO_ID}:v1`,
    videoId: VIDEO_ID,
    kind: "transcript",
    revision: 1,
    storageKey: contextStorageKey,
    contentDigest: sha256(contextBytes),
    byteLength: contextBytes.byteLength,
    createdAt: CONTEXT_AT,
  };
  const fingerprintText = VISUAL_FINGERPRINT_TEXT;
  const fingerprintBytes = Buffer.from(fingerprintText, "utf8");
  const fingerprintStorageKey =
    canonicalChannelPreanalysisVisualFingerprintStorageKey(
      VIDEO_ID,
      AMORETTO_CHANNEL_PREANALYSIS_SOURCE.sourceId,
    );
  const fingerprintArtifact = {
    artifactId: canonicalChannelPreanalysisVisualFingerprintArtifactId(VIDEO_ID),
    videoId: VIDEO_ID,
    kind: "fingerprint",
    revision: 1,
    storageKey: fingerprintStorageKey,
    contentDigest: sha256(fingerprintBytes),
    byteLength: fingerprintBytes.byteLength,
    createdAt: CONTEXT_AT,
  };
  const video = {
    channelId: AMORETTO_CHANNEL_PREANALYSIS_SOURCE.channelId,
    videoId: VIDEO_ID,
    title: TITLE,
    normalizedTitle: normalizeChannelVideoTitle(TITLE),
    durationMs: DURATION_MS,
    publishedAt: PUBLISHED_AT,
    updatedAt: PUBLISHED_AT,
    watchUrl: `https://www.youtube.com/watch?v=${VIDEO_ID}`,
    state: "context-ready",
    revision: 1,
    artifactIds: [contextArtifact.artifactId, fingerprintArtifact.artifactId],
    registeredLocalSampledFingerprints: [],
    retry: null,
  };
  const manifest = {
    schemaVersion: 1,
    channelId: AMORETTO_CHANNEL_PREANALYSIS_SOURCE.channelId,
    channelHandle: AMORETTO_CHANNEL_PREANALYSIS_SOURCE.channelHandle,
    revision: 1,
    generatedAt: CONTEXT_AT,
    videos: [video],
    artifacts: [contextArtifact, fingerprintArtifact],
  };
  parseChannelPreanalysisManifest(serialize(manifest),
    AMORETTO_CHANNEL_PREANALYSIS_SOURCE);
  const contextPath = await writeStorage(
    catalogDir,
    contextStorageKey,
    contextBytes,
  );
  const fingerprintPath = await writeStorage(
    catalogDir,
    fingerprintStorageKey,
    fingerprintBytes,
  );
  await writeFile(join(catalogDir, "catalog.json"), serialize(manifest));
  return {
    catalogDir,
    contextBundle,
    contextBytes,
    contextPath,
    fingerprintBytes,
    fingerprintPath,
    manifest,
    video,
  };
}

function publishInput(fixture) {
  return {
    catalogDir: fixture.catalogDir,
    source: AMORETTO_CHANNEL_PREANALYSIS_SOURCE,
    video: fixture.video,
    contextBundle: fixture.contextBundle,
  };
}

async function assertInputsRemain(fixture) {
  assert.deepEqual(await readFile(fixture.contextPath), fixture.contextBytes);
  assert.deepEqual(await readFile(fixture.fingerprintPath), fixture.fingerprintBytes);
}

test("recovers a verified crash-before-manifest orphan without rerunning review AI", async (t) => {
  const fixture = await createFixture(t);
  const orphan = await verifiedEmptyReview(fixture.contextBundle, 2);
  const reviewStorageKey = channelPreanalysisReviewBundleStorageKey(
    AMORETTO_CHANNEL_PREANALYSIS_SOURCE.sourceId,
    VIDEO_ID,
    2,
  );
  await writeStorage(fixture.catalogDir, reviewStorageKey, serialize(orphan));
  let prepareCalls = 0;

  const result = await publishChannelPreanalysisReview(
    publishInput(fixture),
    {
      prepareReview: async () => {
        prepareCalls += 1;
        throw new Error("orphan recovery must not call the provider");
      },
      nowIso: () => COMMIT_AT,
    },
  );

  assert.equal(result.state, "review-ready");
  assert.equal(result.recovered, true);
  assert.equal(result.reviewBundle.certificate.outcome, "verified-empty");
  assert.equal(prepareCalls, 0);
  const manifest = parseChannelPreanalysisManifest(
    await readFile(join(fixture.catalogDir, "catalog.json"), "utf8"),
    AMORETTO_CHANNEL_PREANALYSIS_SOURCE,
  );
  assert.equal(manifest.videos[0].revision, 2);
  assert.equal(manifest.artifacts.filter(({ kind }) => kind === "review").length, 1);
  await assertInputsRemain(fixture);
});

test("preserves the context checkpoint and source artifacts when review preparation fails", async (t) => {
  const fixture = await createFixture(t);
  let prepareCalls = 0;
  const providerError = Object.assign(new Error("temporary provider outage"), {
    code: "PROVIDER_UNAVAILABLE",
  });

  const result = await publishChannelPreanalysisReview(
    publishInput(fixture),
    {
      prepareReview: async () => {
        prepareCalls += 1;
        throw providerError;
      },
      nowIso: () => COMMIT_AT,
    },
  );

  assert.equal(prepareCalls, 1);
  assert.equal(result.state, "retryable");
  assert.equal(result.errorCode, "PROVIDER_UNAVAILABLE");
  assert.deepEqual(result.video.artifactIds, fixture.video.artifactIds);
  assert.deepEqual(result.video.retry, {
    stage: "review",
    lastSuccessfulState: "context-ready",
    attemptCount: 1,
    nextAttemptAt: "2026-08-02T06:00:00.000Z",
    errorCode: "PROVIDER_UNAVAILABLE",
  });
  assert.equal(result.manifest.artifacts.some(({ kind }) => kind === "review"), false);
  await assertInputsRemain(fixture);
});

test("a review retry reuses the attempted revision so candidate checkpoints remain resumable", async (t) => {
  const fixture = await createFixture(t);
  const failed = await publishChannelPreanalysisReview(
    publishInput(fixture),
    {
      prepareReview: async () => {
        throw Object.assign(new Error("temporary failure"), {
          code: "CANDIDATE_ANALYSIS_FAILED",
        });
      },
      nowIso: () => COMMIT_AT,
    },
  );
  assert.equal(failed.state, "retryable");
  assert.equal(failed.video.revision, 2);

  let resumedRevision = null;
  const resumed = await publishChannelPreanalysisReview(
    {
      catalogDir: fixture.catalogDir,
      source: AMORETTO_CHANNEL_PREANALYSIS_SOURCE,
      video: failed.video,
      contextBundle: fixture.contextBundle,
    },
    {
      prepareReview: async ({ artifactRevision }) => {
        resumedRevision = artifactRevision;
        return verifiedEmptyReview(fixture.contextBundle, artifactRevision);
      },
      nowIso: () => "2026-08-02T07:00:00.000Z",
    },
  );
  assert.equal(resumedRevision, 2);
  assert.equal(resumed.state, "review-ready");
  assert.equal(resumed.video.revision, 2);
});

