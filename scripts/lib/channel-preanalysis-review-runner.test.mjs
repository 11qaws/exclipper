function runnerInput(bundle, overrides = {}) {
  return {
    sourceId: AMORETTO_CHANNEL_PREANALYSIS_SOURCE.sourceId,
    artifactRevision: 1,
    createdAt: CREATED_AT,
    pipelineRevision: "scheduled-review-test-v1",
    bundle,
    audioFeatures: audioFeatures(),
    visualCoverage: visualCoverage(),
    visualCandidateSeeds: [],
    participantGrounding: participantGrounding(),
    extractCandidateMedia: async () => completeMedia(),
    analyzeCandidate: analyzer(),
    candidateConcurrency: 2,
    ...overrides,
  };
}

test("semantic and audio inputs produce one self-contained verified review artifact", async () => {
  const result = await runChannelPreanalysisReview(runnerInput(await contextReadyBundle()));
  assert.equal(result.status, "complete");
  assert.equal(result.reviewBundle.candidates.length, 1);
  assert.equal(result.reviewBundle.certificate.outcome, "review-ready");
  assert.equal(result.reviewBundle.candidates[0].frames.length, 4);
  assert.equal(JSON.stringify(result.reviewBundle).includes("rawAudio"), false);
  assert.equal(result.reviewBundle.participantGrounding.resolutionStatus, "media-reviewed");
  assert.deepEqual(
    result.reviewBundle.participantGrounding.adapterReceipts
      .slice(1)
      .map(({ status, inputCount, processedCount }) => ({
        status,
        inputCount,
        processedCount,
      })),
    [
      { status: "completed", inputCount: 1, processedCount: 1 },
      { status: "completed", inputCount: 1, processedCount: 1 },
    ],
  );
  assert.ok(
    result.reviewBundle.participantGrounding.evidence.some(
      ({ kind }) => kind === "visible-participant-unidentified",
    ),
  );
  assert.ok(
    result.reviewBundle.participantGrounding.evidence.some(
      ({ kind }) => kind === "speaker-unidentified",
    ),
  );
  await verifyChannelPreanalysisReviewBundleIntegrity(result.reviewBundle);
});

