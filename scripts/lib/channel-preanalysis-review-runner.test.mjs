test("a crash resume repeats the durable semantic attempt instead of issuing another charge", async () => {
  const bundle = await contextReadyBundle();
  let aiCalls = 0;
  const persisted = [];
  const first = await runChannelPreanalysisReview(runnerInput(bundle, {
    analyzeCandidate: async (input) => {
      aiCalls += 1;
      if (input.semanticAttempt.attemptOrdinal === 0) {
        return analyzer({ clipDecision: "uncertain" })(input);
      }
      const error = new Error("transport retry budget exhausted");
      error.code = "RETRY_EXHAUSTED";
      throw error;
    },
    onCandidateCheckpoint: async (checkpoint) => {
      persisted.push(checkpoint);
    },
  }));
  assert.equal(first.status, "incomplete");
  assert.equal(first.candidateResults[0].status, "retryable");
  assert.equal(first.candidateResults[0].attemptOrdinal, 1);
  assert.notEqual(first.candidateResults[0].retryGrantId, null);
  assert.equal(
    first.candidateResults[0].lastRecord.verificationReceipt.dispatchIntent
      .attemptOrdinal,
    0,
  );
  assert.equal(persisted.at(-1).status, "retryable");

  let resumedAttempt = null;
  const recovered = await runChannelPreanalysisReview(runnerInput(bundle, {
    previousCandidateResults: first.candidateResults,
    analyzeCandidate: async (input) => {
      aiCalls += 1;
      resumedAttempt = input.semanticAttempt;
      return analyzer()(input);
    },
  }));
  assert.equal(aiCalls, 3);
  assert.deepEqual(resumedAttempt, {
    attemptOrdinal: 1,
    retryGrantId: first.candidateResults[0].retryGrantId,
  });
  assert.equal(recovered.status, "complete");
  assert.equal(recovered.reviewBundle.certificate.outcome, "review-ready");
  assert.equal(recovered.candidateResults[0].attemptOrdinal, 1);
  assert.equal(recovered.candidateResults[0].resolution, "publish");
});

