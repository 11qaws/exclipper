test("a source with complete static visual coverage and no other lead is verified-empty", async () => {
  let mediaCalls = 0;
  const result = await runChannelPreanalysisReview(
    runnerInput(await contextReadyBundle([]), {
      extractCandidateMedia: async () => {
        mediaCalls += 1;
        return completeMedia();
      },
      analyzeCandidate: async () => assert.fail("AI must not run without candidates"),
    }),
  );
  assert.equal(result.status, "complete");
  assert.equal(result.reviewBundle.certificate.outcome, "verified-empty");
  assert.deepEqual(result.reviewBundle.candidates, []);
  assert.equal(result.reviewBundle.participantGrounding.resolutionStatus, "media-reviewed");
  assert.ok(
    result.reviewBundle.participantGrounding.adapterReceipts
      .slice(1)
      .every(({ status, inputCount }) => status === "completed" && inputCount === 0),
  );
  assert.equal(mediaCalls, 0);
});

test("a quiet visual event enters four-frame AI verification without an audio or semantic lead", async () => {
  let aiCalls = 0;
  const result = await runChannelPreanalysisReview(
    runnerInput(await contextReadyBundle([]), {
      visualCoverage: visualCoverage(1),
      visualCandidateSeeds: [quietVisualSeed()],
      analyzeCandidate: async (input) => {
        aiCalls += 1;
        assert.deepEqual(input.candidate.sourceKinds, ["visual"]);
        assert.equal(input.frames.length, 4);
        return analyzer()(input);
      },
    }),
  );
  assert.equal(aiCalls, 1);
  assert.equal(result.status, "complete");
  assert.equal(result.reviewBundle.certificate.outcome, "review-ready");
  assert.equal(result.reviewBundle.visualCoverage.visualSeedCount, 1);
});

test("three frames stop that candidate before AI and preserve a retry checkpoint", async () => {
  let aiCalls = 0;
  const result = await runChannelPreanalysisReview(
    runnerInput(await contextReadyBundle(), {
      extractCandidateMedia: async () => ({
        ...completeMedia(),
        frames: completeMedia().frames.slice(0, 3),
      }),
      analyzeCandidate: async () => {
        aiCalls += 1;
        return analyzer()();
      },
    }),
  );
  assert.equal(result.status, "incomplete");
  assert.equal(result.reviewBundle, null);
  assert.equal(result.candidateResults[0].status, "retryable");
  assert.equal(result.candidateResults[0].errorCode, "FRAME_BUNDLE_INCOMPLETE");
  assert.equal(aiCalls, 0);
});

test("AI-confirmed music is a terminal exclusion and can yield verified-empty", async () => {
  const result = await runChannelPreanalysisReview(
    runnerInput(await contextReadyBundle(), {
      analyzeCandidate: analyzer({
        clipDecision: "reject",
        programMaterial: "music-or-intermission",
      }),
    }),
  );
  assert.equal(result.status, "complete");
  assert.equal(result.reviewBundle.certificate.outcome, "verified-empty");
  assert.equal(result.candidateResults[0].status, "analyzed");
});

test("completed per-candidate checkpoints skip media extraction and AI on resume", async () => {
  const bundle = await contextReadyBundle();
  const first = await runChannelPreanalysisReview(runnerInput(bundle));
  let calls = 0;
  const resumed = await runChannelPreanalysisReview(
    runnerInput(bundle, {
      previousCandidateResults: first.candidateResults,
      extractCandidateMedia: async () => {
        calls += 1;
        return completeMedia();
      },
      analyzeCandidate: async () => {
        calls += 1;
        return null;
      },
    }),
  );
  assert.equal(resumed.status, "complete");
  assert.equal(calls, 0);
  assert.deepEqual(resumed.reviewBundle, first.reviewBundle);
});
