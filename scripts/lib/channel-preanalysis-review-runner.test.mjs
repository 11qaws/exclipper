function audioFeaturesFor(durationMs, reactionStartIndices = []) {
  const windowCount = durationMs / 1_000;
  const windows = Array.from({ length: windowCount }, (_, index) => {
    const rms = 0.055 + (index % 4) * 0.002;
    return {
      startMs: index * 1_000,
      endMs: (index + 1) * 1_000,
      rms,
      peak: Math.min(1, rms * 3),
      zeroCrossingRate: 0.09 + (index % 3) * 0.005,
      speechBandEnergyRatio: 0.52,
    };
  });
  for (const startIndex of reactionStartIndices) {
    [0.18, 0.25, 0.17, 0.23].forEach((rms, offset) => {
      const index = startIndex + offset;
      windows[index] = {
        startMs: index * 1_000,
        endMs: (index + 1) * 1_000,
        rms,
        peak: Math.min(0.92, rms * 3.1),
        zeroCrossingRate: 0.14 + (offset % 3) * 0.035,
        speechBandEnergyRatio: 0.72 + (offset % 2) * 0.08,
      };
    });
  }
  return {
    sourceDurationMs: durationMs,
    plannedWindowCount: windowCount,
    analyzedWindowCount: windowCount,
    coverageComplete: true,
    windows,
  };
}

