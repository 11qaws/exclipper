async function buildRouteEntry(
  ordinal: number,
  binding: {
    readonly sourceFingerprint: string;
    readonly sourceDurationMs: number;
    readonly selectedLeadPlan: DiscoveredLeadRefinementPlan;
    readonly selectedLeadPlanFingerprint: string;
  },
  input: AppendBroadcastRefinementEvidenceInput,
  digestAdapter: ContentDigestAdapter,
): Promise<BroadcastRefinementEvidenceRouteEntry> {
  let withoutFingerprint: Omit<
    BroadcastRefinementEvidenceRouteEntry,
    "entryFingerprint"
  >;
  if (input.routeKind === "youtube-caption") {
    if (!isBoundedString(input.captionRevision, 512)) {
      throw new BroadcastRefinementEvidenceLedgerError(
        "INVALID_LEDGER",
        "The caption revision is invalid.",
      );
    }
    const track = normalizedCaptionTrack(
      input.captionTrack,
      binding.sourceDurationMs,
    );
    const verifiedNoSpeechEvidence =
      normalizedCaptionSpeechActivityEvidence(
        input.verifiedNoSpeechEvidence,
        binding.selectedLeadPlan,
        binding.sourceDurationMs,
      );
    const settlements = createBroadcastRefinementCaptionCellSettlements({
      sourceDurationMs: binding.sourceDurationMs,
      selectedLeadPlan: binding.selectedLeadPlan,
      captionTrack: track,
      verifiedNoSpeechEvidence,
    });
    const canonicalSettlements = normalizedCaptionSettlements(
      settlements,
      binding.selectedLeadPlan,
      new Set(verifiedNoSpeechEvidence.map(({ segmentId }) => segmentId)),
    );
    const expectedTranscriptByRange = new Map(
      createYouTubeCaptionRefinementTranscripts(
        track,
        binding.selectedLeadPlan,
      ).map((transcript) => [
        `${transcript.sourceStartMs}:${transcript.sourceEndMs}`,
        transcript.textKo,
      ]),
    );
    if (
      canonicalSettlements.some(
        (settlement) =>
          settlement.status === "success" &&
          expectedTranscriptByRange.get(
            `${settlement.sourceStartMs}:${settlement.sourceEndMs}`,
          ) !== settlement.textKo,
      )
    ) {
      throw new BroadcastRefinementEvidenceLedgerError(
        "INVALID_LEDGER",
        "Caption success evidence must exactly match its fenced event source.",
      );
    }
    const successCount = canonicalSettlements.filter(
      ({ status }) => status === "success",
    ).length;
    const resolvedCount = canonicalSettlements.filter(
      ({ status }) => status === "resolved",
    ).length;
    const gapCount = canonicalSettlements.filter(
      ({ status }) => status === "gap",
    ).length;
    withoutFingerprint = {
      ordinal,
      routeKind: "youtube-caption",
      billingClass: "free",
      sourceFingerprint: binding.sourceFingerprint,
      sourceDurationMs: binding.sourceDurationMs,
      selectedLeadPlanFingerprint: binding.selectedLeadPlanFingerprint,
      evidenceRevision: input.captionRevision,
      captionEventSourceFence: await captionEventSourceFence(
        binding.sourceFingerprint,
        binding.sourceDurationMs,
        binding.selectedLeadPlanFingerprint,
        input.captionRevision,
        track,
        digestAdapter,
      ),
      providerReceiptCheckpointSignature: null,
      captionSource: {
        videoId: track.videoId,
        languageCode: track.languageCode,
        isAutoGenerated: track.isAutoGenerated,
      },
      evidencePayload: {
        kind: "youtube-caption-cells",
        settlements: canonicalSettlements,
        verifiedNoSpeechEvidence,
      },
      settlement: settlementSummary(
        binding.selectedLeadPlan.segments.length,
        successCount,
        resolvedCount,
        gapCount,
      ),
    };
  } else {
    const asr = validatedAsrPayload(
      input.refinementCheckpoint,
      input.providerReceiptCheckpoint,
      binding.selectedLeadPlan,
      binding.sourceFingerprint,
      binding.sourceDurationMs,
    );
    withoutFingerprint = {
      ordinal,
      routeKind: "asr",
      billingClass: input.billingClass,
      sourceFingerprint: binding.sourceFingerprint,
      sourceDurationMs: binding.sourceDurationMs,
      selectedLeadPlanFingerprint: binding.selectedLeadPlanFingerprint,
      evidenceRevision: asr.evidenceRevision,
      captionEventSourceFence: null,
      providerReceiptCheckpointSignature: await providerCheckpointSignature(
        asr.payload.providerReceiptCheckpoint,
        digestAdapter,
      ),
      captionSource: null,
      evidencePayload: asr.payload,
      settlement: asr.settlement,
    };
  }
  return {
    entryFingerprint: await routeEntryFingerprint(
      routeEntryFingerprintPayload(withoutFingerprint),
      digestAdapter,
    ),
    ...withoutFingerprint,
  };
}

async function normalizedStoredRouteEntry(
  value: unknown,
  ordinal: number,
  binding: {
    readonly sourceFingerprint: string;
    readonly sourceDurationMs: number;
    readonly selectedLeadPlan: DiscoveredLeadRefinementPlan;
    readonly selectedLeadPlanFingerprint: string;
  },
  digestAdapter: ContentDigestAdapter,
): Promise<BroadcastRefinementEvidenceRouteEntry> {
  if (
    !isRecord(value) ||
    !hasExactKeys(value, [
      "entryFingerprint",
      "ordinal",
      "routeKind",
      "billingClass",
      "sourceFingerprint",
      "sourceDurationMs",
      "selectedLeadPlanFingerprint",
      "evidenceRevision",
      "captionEventSourceFence",
      "providerReceiptCheckpointSignature",
      "captionSource",
      "evidencePayload",
      "settlement",
    ]) ||
    !isSha256(value.entryFingerprint) ||
    value.ordinal !== ordinal ||
    value.sourceFingerprint !== binding.sourceFingerprint ||
    value.sourceDurationMs !== binding.sourceDurationMs ||
    value.selectedLeadPlanFingerprint !==
      binding.selectedLeadPlanFingerprint ||
    !isBoundedString(value.evidenceRevision, 512) ||
    !isRecord(value.evidencePayload) ||
    !isRecord(value.settlement)
  ) {
    throw new BroadcastRefinementEvidenceLedgerError(
      "INVALID_LEDGER",
      "A refinement evidence route entry has an invalid source or plan fence.",
    );
  }
  let canonical: BroadcastRefinementEvidenceRouteEntry;
  if (value.routeKind === "youtube-caption") {
    if (
      value.billingClass !== "free" ||
      !isSha256(value.captionEventSourceFence) ||
      value.providerReceiptCheckpointSignature !== null ||
      !isRecord(value.captionSource) ||
      !hasExactKeys(value.captionSource, [
        "videoId",
        "languageCode",
        "isAutoGenerated",
      ]) ||
      typeof value.captionSource.videoId !== "string" ||
      !YOUTUBE_VIDEO_ID_PATTERN.test(value.captionSource.videoId) ||
      !isBoundedString(value.captionSource.languageCode, 35) ||
      typeof value.captionSource.isAutoGenerated !== "boolean" ||
      !hasExactKeys(value.evidencePayload, [
        "kind",
        "settlements",
        "verifiedNoSpeechEvidence",
      ]) ||
      value.evidencePayload.kind !== "youtube-caption-cells"
    ) {
      throw new BroadcastRefinementEvidenceLedgerError(
        "INVALID_LEDGER",
        "A caption route entry has an invalid event-source fence.",
      );
    }
    const verifiedNoSpeechEvidence =
      normalizedCaptionSpeechActivityEvidence(
        value.evidencePayload.verifiedNoSpeechEvidence,
        binding.selectedLeadPlan,
        binding.sourceDurationMs,
      );
    const settlements = normalizedCaptionSettlements(
      value.evidencePayload.settlements,
      binding.selectedLeadPlan,
      new Set(verifiedNoSpeechEvidence.map(({ segmentId }) => segmentId)),
    );
    const summary = settlementSummary(
      binding.selectedLeadPlan.segments.length,
      settlements.filter(({ status }) => status === "success").length,
      settlements.filter(({ status }) => status === "resolved").length,
      settlements.filter(({ status }) => status === "gap").length,
    );
    canonical = {
      entryFingerprint: value.entryFingerprint,
      ordinal,
      routeKind: "youtube-caption",
      billingClass: "free",
      sourceFingerprint: binding.sourceFingerprint,
      sourceDurationMs: binding.sourceDurationMs,
      selectedLeadPlanFingerprint: binding.selectedLeadPlanFingerprint,
      evidenceRevision: value.evidenceRevision,
      captionEventSourceFence: value.captionEventSourceFence,
      providerReceiptCheckpointSignature: null,
      captionSource: {
        videoId: value.captionSource.videoId,
        languageCode: value.captionSource.languageCode,
        isAutoGenerated: value.captionSource.isAutoGenerated,
      },
      evidencePayload: {
        kind: "youtube-caption-cells",
        settlements,
        verifiedNoSpeechEvidence,
      },
      settlement: summary,
    };
  } else if (value.routeKind === "asr") {
    if (
      (value.billingClass !== "free" && value.billingClass !== "paid") ||
      value.captionEventSourceFence !== null ||
      value.captionSource !== null ||
      !isSha256(value.providerReceiptCheckpointSignature) ||
      !hasExactKeys(value.evidencePayload, [
        "kind",
        "refinementCheckpoint",
        "providerReceiptCheckpoint",
      ]) ||
      value.evidencePayload.kind !== "asr-refinement-checkpoints"
    ) {
      throw new BroadcastRefinementEvidenceLedgerError(
        "INVALID_LEDGER",
        "An ASR route entry has an invalid provider checkpoint fence.",
      );
    }
    const asr = validatedAsrPayload(
      value.evidencePayload
        .refinementCheckpoint as BroadcastRefinementTranscriptCheckpoint,
      value.evidencePayload
        .providerReceiptCheckpoint as BroadcastTranscriptProviderReceiptCheckpoint,
      binding.selectedLeadPlan,
      binding.sourceFingerprint,
      binding.sourceDurationMs,
    );
    const expectedProviderSignature = await providerCheckpointSignature(
      asr.payload.providerReceiptCheckpoint,
      digestAdapter,
    );
    if (
      value.evidenceRevision !== asr.evidenceRevision ||
      value.providerReceiptCheckpointSignature !== expectedProviderSignature
    ) {
      throw new BroadcastRefinementEvidenceLedgerError(
        "INVALID_LEDGER",
        "The ASR route revision or provider checkpoint signature is stale.",
      );
    }
    canonical = {
      entryFingerprint: value.entryFingerprint,
      ordinal,
      routeKind: "asr",
      billingClass: value.billingClass,
      sourceFingerprint: binding.sourceFingerprint,
      sourceDurationMs: binding.sourceDurationMs,
      selectedLeadPlanFingerprint: binding.selectedLeadPlanFingerprint,
      evidenceRevision: asr.evidenceRevision,
      captionEventSourceFence: null,
      providerReceiptCheckpointSignature: expectedProviderSignature,
      captionSource: null,
      evidencePayload: asr.payload,
      settlement: asr.settlement,
    };
  } else {
    throw new BroadcastRefinementEvidenceLedgerError(
      "INVALID_LEDGER",
      "The refinement evidence route kind is unknown.",
    );
  }
  if (JSON.stringify(canonical.settlement) !== JSON.stringify(value.settlement)) {
    throw new BroadcastRefinementEvidenceLedgerError(
      "INVALID_LEDGER",
      "The stored route settlement summary is not derived from its cells.",
    );
  }
  if (
    canonical.entryFingerprint !==
    (await routeEntryFingerprint(
      routeEntryFingerprintPayload(canonical),
      digestAdapter,
    ))
  ) {
    throw new BroadcastRefinementEvidenceLedgerError(
      "INVALID_LEDGER",
      "The refinement evidence route entry fingerprint is invalid.",
    );
  }
  return canonical;
}

async function normalizedLedger(
  value: unknown,
  digestAdapter: ContentDigestAdapter,
): Promise<BroadcastRefinementEvidenceLedger> {
  if (
    !isRecord(value) ||
    !hasExactKeys(value, [
      "schemaVersion",
      "generation",
      "sourceFingerprint",
      "sourceDurationMs",
      "selectedLeadPlan",
      "selectedLeadPlanFingerprint",
      "activeRouteEntryFingerprint",
      "activeRouteProjectionFingerprint",
      "routeEntries",
      "ledgerFingerprint",
    ]) ||
    value.schemaVersion !==
      BROADCAST_REFINEMENT_EVIDENCE_LEDGER_SCHEMA_VERSION ||
    !Number.isSafeInteger(value.generation) ||
    (value.generation as number) < 0 ||
    (value.generation as number) > MAX_GENERATION ||
    !isBoundedString(value.sourceFingerprint) ||
    !Number.isSafeInteger(value.sourceDurationMs) ||
    (value.sourceDurationMs as number) <= 0 ||
    (value.sourceDurationMs as number) >
      MAX_BROADCAST_CONTEXT_SOURCE_DURATION_MS ||
    !isSha256(value.selectedLeadPlanFingerprint) ||
    !(value.activeRouteEntryFingerprint === null ||
      isSha256(value.activeRouteEntryFingerprint)) ||
    !(value.activeRouteProjectionFingerprint === null ||
      isSha256(value.activeRouteProjectionFingerprint)) ||
    !Array.isArray(value.routeEntries) ||
    value.routeEntries.length >
      MAX_BROADCAST_REFINEMENT_EVIDENCE_ROUTE_ENTRIES ||
    !isSha256(value.ledgerFingerprint)
  ) {
    throw new BroadcastRefinementEvidenceLedgerError(
      "INVALID_LEDGER",
      "The refinement evidence ledger failed its exact outer contract.",
    );
  }
  const sourceDurationMs = value.sourceDurationMs as number;
  const selectedLeadPlan = normalizedSelectedLeadPlan(
    value.selectedLeadPlan,
    sourceDurationMs,
  );
  const expectedPlanFingerprint = await selectedLeadPlanFingerprint(
    value.sourceFingerprint,
    sourceDurationMs,
    selectedLeadPlan,
    digestAdapter,
  );
  if (value.selectedLeadPlanFingerprint !== expectedPlanFingerprint) {
    throw new BroadcastRefinementEvidenceLedgerError(
      "INVALID_LEDGER",
      "The selected lead plan fingerprint is invalid.",
    );
  }
  const rawEntries: readonly unknown[] = value.routeEntries;
  const binding = {
    sourceFingerprint: value.sourceFingerprint,
    sourceDurationMs,
    selectedLeadPlan,
    selectedLeadPlanFingerprint: expectedPlanFingerprint,
  };
  const routeEntries: BroadcastRefinementEvidenceRouteEntry[] = [];
  for (const [ordinal, raw] of rawEntries.entries()) {
    routeEntries.push(
      await normalizedStoredRouteEntry(
        raw,
        ordinal,
        binding,
        digestAdapter,
      ),
    );
  }
  if (
    new Set(routeEntries.map(({ entryFingerprint }) => entryFingerprint))
      .size !== routeEntries.length
  ) {
    throw new BroadcastRefinementEvidenceLedgerError(
      "INVALID_LEDGER",
      "A refinement evidence ledger cannot repeat a route entry.",
    );
  }
  const activeEntry =
    value.activeRouteEntryFingerprint === null
      ? null
      : routeEntries.find(
          ({ entryFingerprint }) =>
            entryFingerprint === value.activeRouteEntryFingerprint,
        ) ?? null;
  if (
    (value.activeRouteEntryFingerprint === null) !== (activeEntry === null)
  ) {
    throw new BroadcastRefinementEvidenceLedgerError(
      "INVALID_LEDGER",
      "The active refinement route does not exist in this ledger.",
    );
  }
  const expectedActiveProjectionFingerprint =
    activeEntry === null
      ? null
      : await activeProjectionFingerprint(
          binding.sourceFingerprint,
          binding.sourceDurationMs,
          binding.selectedLeadPlanFingerprint,
          activeEntry.entryFingerprint,
          digestAdapter,
        );
  if (
    value.activeRouteProjectionFingerprint !==
    expectedActiveProjectionFingerprint
  ) {
    throw new BroadcastRefinementEvidenceLedgerError(
      "INVALID_LEDGER",
      "The active refinement route projection fingerprint is invalid.",
    );
  }
  const withoutFingerprint: Omit<
    BroadcastRefinementEvidenceLedger,
    "ledgerFingerprint"
  > = {
    schemaVersion:
      BROADCAST_REFINEMENT_EVIDENCE_LEDGER_SCHEMA_VERSION,
    generation: value.generation as number,
    sourceFingerprint: binding.sourceFingerprint,
    sourceDurationMs: binding.sourceDurationMs,
    selectedLeadPlan: binding.selectedLeadPlan,
    selectedLeadPlanFingerprint: binding.selectedLeadPlanFingerprint,
    activeRouteEntryFingerprint:
      activeEntry?.entryFingerprint ?? null,
    activeRouteProjectionFingerprint:
      expectedActiveProjectionFingerprint,
    routeEntries,
  };
  const expectedLedgerFingerprint = await ledgerFingerprint(
    withoutFingerprint,
    digestAdapter,
  );
  if (value.ledgerFingerprint !== expectedLedgerFingerprint) {
    throw new BroadcastRefinementEvidenceLedgerError(
      "INVALID_LEDGER",
      "The refinement evidence ledger fingerprint is invalid.",
    );
  }
  return {
    ...withoutFingerprint,
    ledgerFingerprint: expectedLedgerFingerprint,
  };
}

async function builtLedger(
  input: Omit<BroadcastRefinementEvidenceLedger, "ledgerFingerprint">,
  digestAdapter: ContentDigestAdapter,
): Promise<BroadcastRefinementEvidenceLedger> {
  const withoutFingerprint: Omit<
    BroadcastRefinementEvidenceLedger,
    "ledgerFingerprint"
  > = {
    schemaVersion: input.schemaVersion,
    generation: input.generation,
    sourceFingerprint: input.sourceFingerprint,
    sourceDurationMs: input.sourceDurationMs,
    selectedLeadPlan: input.selectedLeadPlan,
    selectedLeadPlanFingerprint: input.selectedLeadPlanFingerprint,
    activeRouteEntryFingerprint: input.activeRouteEntryFingerprint,
    activeRouteProjectionFingerprint:
      input.activeRouteProjectionFingerprint,
    routeEntries: input.routeEntries,
  };
  const result = {
    ...withoutFingerprint,
    ledgerFingerprint: await ledgerFingerprint(
      withoutFingerprint,
      digestAdapter,
    ),
  };
  const normalized = await normalizedLedger(result, digestAdapter);
  if (
    utf8ByteLength(JSON.stringify(normalized)) >
    MAX_BROADCAST_REFINEMENT_EVIDENCE_LEDGER_BYTES
  ) {
    throw new BroadcastRefinementEvidenceLedgerError(
      "ROUTE_ENTRY_LIMIT",
      "The refinement evidence ledger exceeds its byte limit.",
    );
  }
  return normalized;
}

async function currentLedgerForCas(
  ledger: BroadcastRefinementEvidenceLedger,
  expectedLedgerFingerprint: string,
  digestAdapter: ContentDigestAdapter,
): Promise<BroadcastRefinementEvidenceLedger> {
  const current = await normalizedLedger(ledger, digestAdapter);
  if (
    !isSha256(expectedLedgerFingerprint) ||
    current.ledgerFingerprint !== expectedLedgerFingerprint
  ) {
    throw new BroadcastRefinementEvidenceLedgerError(
      "CAS_MISMATCH",
      "The refinement evidence ledger changed before this update.",
    );
  }
  return current;
}

async function assertInputBinding(
  ledger: BroadcastRefinementEvidenceLedger,
  input: BroadcastRefinementEvidenceLedgerBinding,
  digestAdapter: ContentDigestAdapter,
): Promise<void> {
  let inputPlan: DiscoveredLeadRefinementPlan;
  try {
    inputPlan = normalizedSelectedLeadPlan(
      input.selectedLeadPlan,
      input.sourceDurationMs,
    );
  } catch {
    throw new BroadcastRefinementEvidenceLedgerError(
      "STALE_BINDING",
      "The proposed route does not carry the current selected lead plan.",
    );
  }
  const inputPlanFingerprint = await selectedLeadPlanFingerprint(
    input.sourceFingerprint,
    input.sourceDurationMs,
    inputPlan,
    digestAdapter,
  );
  if (
    input.sourceFingerprint !== ledger.sourceFingerprint ||
    input.sourceDurationMs !== ledger.sourceDurationMs ||
    inputPlanFingerprint !== ledger.selectedLeadPlanFingerprint ||
    JSON.stringify(inputPlan) !== JSON.stringify(ledger.selectedLeadPlan)
  ) {
    throw new BroadcastRefinementEvidenceLedgerError(
      "STALE_BINDING",
      "The proposed route belongs to a stale source or selected lead plan.",
    );
  }
}

export async function createBroadcastRefinementEvidenceLedger(
  input: BroadcastRefinementEvidenceLedgerBinding,
  digestAdapter: ContentDigestAdapter | null = globalThis.crypto?.subtle ??
    null,
): Promise<BroadcastRefinementEvidenceLedger> {
  const digest = requireDigest(digestAdapter);
  if (
    !isBoundedString(input.sourceFingerprint) ||
    !Number.isSafeInteger(input.sourceDurationMs) ||
    input.sourceDurationMs <= 0 ||
    input.sourceDurationMs > MAX_BROADCAST_CONTEXT_SOURCE_DURATION_MS
  ) {
    throw new BroadcastRefinementEvidenceLedgerError(
      "INVALID_LEDGER",
      "The refinement evidence ledger requires an exact bounded source.",
    );
  }
  const selectedLeadPlan = normalizedSelectedLeadPlan(
    input.selectedLeadPlan,
    input.sourceDurationMs,
  );
  const planFingerprint = await selectedLeadPlanFingerprint(
    input.sourceFingerprint,
    input.sourceDurationMs,
    selectedLeadPlan,
    digest,
  );
  return builtLedger(
    {
      schemaVersion:
        BROADCAST_REFINEMENT_EVIDENCE_LEDGER_SCHEMA_VERSION,
      generation: 0,
      sourceFingerprint: input.sourceFingerprint,
      sourceDurationMs: input.sourceDurationMs,
      selectedLeadPlan,
      selectedLeadPlanFingerprint: planFingerprint,
      activeRouteEntryFingerprint: null,
      activeRouteProjectionFingerprint: null,
      routeEntries: [],
    },
    digest,
  );
}

/**
 * Append-only route update. Exact duplicate entries are idempotent; a changed
 * evidence payload becomes a new entry, preserving every previous paid/free
 * route for later reactivation.
 */
export async function appendBroadcastRefinementEvidenceRouteEntry(
  ledger: BroadcastRefinementEvidenceLedger,
  expectedLedgerFingerprint: string,
  input: AppendBroadcastRefinementEvidenceInput,
  digestAdapter: ContentDigestAdapter | null = globalThis.crypto?.subtle ??
    null,
): Promise<AppendBroadcastRefinementEvidenceRouteEntryResult> {
  const digest = requireDigest(digestAdapter);
  const current = await currentLedgerForCas(
    ledger,
    expectedLedgerFingerprint,
    digest,
  );
  await assertInputBinding(current, input, digest);
  const routeEntry = await buildRouteEntry(
    current.routeEntries.length,
    {
      sourceFingerprint: current.sourceFingerprint,
      sourceDurationMs: current.sourceDurationMs,
      selectedLeadPlan: current.selectedLeadPlan,
      selectedLeadPlanFingerprint: current.selectedLeadPlanFingerprint,
    },
    input,
    digest,
  );
  const duplicate = current.routeEntries.find(
    ({ entryFingerprint }) =>
      entryFingerprint === routeEntry.entryFingerprint,
  );
  if (duplicate !== undefined) {
    return {
      ledger: current,
      routeEntryFingerprint: duplicate.entryFingerprint,
      appended: false,
    };
  }
  if (
    current.routeEntries.length >=
    MAX_BROADCAST_REFINEMENT_EVIDENCE_ROUTE_ENTRIES
  ) {
    throw new BroadcastRefinementEvidenceLedgerError(
      "ROUTE_ENTRY_LIMIT",
      "The refinement evidence route history is full.",
    );
  }
  const nextLedger = await builtLedger(
    {
      ...current,
      generation: current.generation + 1,
      routeEntries: [...current.routeEntries, routeEntry],
    },
    digest,
  );
  return {
    ledger: nextLedger,
    routeEntryFingerprint: routeEntry.entryFingerprint,
    appended: true,
  };
}

/**
 * Changes only the active pointer and projection cache key. Route entries are
 * never deleted or relabeled by activation.
 */
export async function activateBroadcastRefinementEvidenceRoute(
  ledger: BroadcastRefinementEvidenceLedger,
  expectedLedgerFingerprint: string,
  routeEntryFingerprint: string,
  digestAdapter: ContentDigestAdapter | null = globalThis.crypto?.subtle ??
    null,
): Promise<BroadcastRefinementEvidenceLedger> {
  const digest = requireDigest(digestAdapter);
  const current = await currentLedgerForCas(
    ledger,
    expectedLedgerFingerprint,
    digest,
  );
  const entry = current.routeEntries.find(
    ({ entryFingerprint }) =>
      entryFingerprint === routeEntryFingerprint,
  );
  if (entry === undefined) {
    throw new BroadcastRefinementEvidenceLedgerError(
      "UNKNOWN_ROUTE_ENTRY",
      "The requested refinement evidence route is not in this ledger.",
    );
  }
  if (current.activeRouteEntryFingerprint === entry.entryFingerprint) {
    return current;
  }
  return builtLedger(
    {
      ...current,
      generation: current.generation + 1,
      activeRouteEntryFingerprint: entry.entryFingerprint,
      activeRouteProjectionFingerprint: await activeProjectionFingerprint(
        current.sourceFingerprint,
        current.sourceDurationMs,
        current.selectedLeadPlanFingerprint,
        entry.entryFingerprint,
        digest,
      ),
    },
    digest,
  );
}

export function projectBroadcastRefinementActiveEvidenceRoute(
  ledger: BroadcastRefinementEvidenceLedger,
): BroadcastRefinementActiveRouteProjection | null {
  if (
    ledger.activeRouteEntryFingerprint === null ||
    ledger.activeRouteProjectionFingerprint === null
  ) {
    return null;
  }
  const entry = ledger.routeEntries.find(
    ({ entryFingerprint }) =>
      entryFingerprint === ledger.activeRouteEntryFingerprint,
  );
  if (entry === undefined) return null;
  return {
    projectionFingerprint: ledger.activeRouteProjectionFingerprint,
    routeEntryFingerprint: entry.entryFingerprint,
    routeKind: entry.routeKind,
    billingClass: entry.billingClass,
    evidenceRevision: entry.evidenceRevision,
    publicationEligible: entry.settlement.publicationEligible,
  };
}

export function getBroadcastRefinementActiveEvidencePayload(
  ledger: BroadcastRefinementEvidenceLedger,
): BroadcastRefinementActiveEvidencePayloadProjection | null {
  if (
    ledger.activeRouteEntryFingerprint === null ||
    ledger.activeRouteProjectionFingerprint === null
  ) {
    return null;
  }
  const entry = ledger.routeEntries.find(
    ({ entryFingerprint }) =>
      entryFingerprint === ledger.activeRouteEntryFingerprint,
  );
  if (entry === undefined) return null;
  return {
    routeEntryFingerprint: entry.entryFingerprint,
    routeKind: entry.routeKind,
    billingClass: entry.billingClass,
    evidencePayload: entry.evidencePayload,
    settlement: entry.settlement,
  };
}

export function broadcastRefinementEvidenceLedgerCanPublish(
  ledger: BroadcastRefinementEvidenceLedger,
): boolean {
  return (
    projectBroadcastRefinementActiveEvidenceRoute(ledger)
      ?.publicationEligible === true
  );
}

export async function serializeBroadcastRefinementEvidenceLedger(
  ledger: BroadcastRefinementEvidenceLedger,
  digestAdapter: ContentDigestAdapter | null = globalThis.crypto?.subtle ??
    null,
): Promise<string> {
  const normalized = await normalizedLedger(
    ledger,
    requireDigest(digestAdapter),
  );
  const serialized = JSON.stringify(normalized);
  if (
    utf8ByteLength(serialized) >
    MAX_BROADCAST_REFINEMENT_EVIDENCE_LEDGER_BYTES
  ) {
    throw new BroadcastRefinementEvidenceLedgerError(
      "ROUTE_ENTRY_LIMIT",
      "The refinement evidence ledger exceeds its byte limit.",
    );
  }
  return serialized;
}

export async function parseBroadcastRefinementEvidenceLedgerJson(
  serialized: string,
  digestAdapter: ContentDigestAdapter | null = globalThis.crypto?.subtle ??
    null,
): Promise<BroadcastRefinementEvidenceLedger | null> {
  if (
    typeof serialized !== "string" ||
    serialized.length === 0 ||
    utf8ByteLength(serialized) >
      MAX_BROADCAST_REFINEMENT_EVIDENCE_LEDGER_BYTES
  ) {
    return null;
  }
  try {
    const parsed: unknown = JSON.parse(serialized);
    const normalized = await normalizedLedger(
      parsed,
      requireDigest(digestAdapter),
    );
    return JSON.stringify(normalized) === serialized ? normalized : null;
  } catch {
    return null;
  }
}
