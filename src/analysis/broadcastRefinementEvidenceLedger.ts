function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

function hasExactKeys(
  value: Readonly<Record<string, unknown>>,
  expectedKeys: readonly string[],
): boolean {
  const actual = Object.keys(value).sort();
  const expected = [...expectedKeys].sort();
  return (
    actual.length === expected.length &&
    actual.every((key, index) => key === expected[index])
  );
}

function isBoundedString(
  value: unknown,
  maximumLength = MAX_FENCE_LENGTH,
): value is string {
  return (
    typeof value === "string" &&
    value.length > 0 &&
    value.length <= maximumLength &&
    value.trim() === value &&
    !/[\p{Cc}\p{Cf}]/u.test(value)
  );
}

function isSha256(value: unknown): value is string {
  return typeof value === "string" && SHA256_PATTERN.test(value);
}

function utf8ByteLength(value: string): number {
  return new TextEncoder().encode(value).byteLength;
}

function requireDigest(
  digestAdapter: ContentDigestAdapter | null,
): ContentDigestAdapter {
  if (digestAdapter === null) {
    throw new BroadcastRefinementEvidenceLedgerError(
      "INVALID_LEDGER",
      "SHA-256 is required for refinement evidence ledger fences.",
    );
  }
  return digestAdapter;
}

function normalizedSelectedLeadPlan(
  value: unknown,
  sourceDurationMs: number,
): DiscoveredLeadRefinementPlan {
  if (
    !isRecord(value) ||
    !hasExactKeys(value, [
      "version",
      "selectedLeadIds",
      "segments",
      "estimatedAsrCostUsd",
    ]) ||
    value.version !== DISCOVERED_LEAD_REFINEMENT_VERSION ||
    !Array.isArray(value.selectedLeadIds) ||
    !Array.isArray(value.segments) ||
    value.selectedLeadIds.length > MAX_CAPTION_DISCOVERED_LEADS_TO_REFINE ||
    value.segments.length > MAX_BROADCAST_TRANSCRIPT_WORKER_CHUNKS ||
    typeof value.estimatedAsrCostUsd !== "number" ||
    !Number.isFinite(value.estimatedAsrCostUsd) ||
    value.estimatedAsrCostUsd < 0 ||
    value.estimatedAsrCostUsd >
      DISCOVERED_LEAD_REFINEMENT_BUDGET_USD + Number.EPSILON
  ) {
    throw new BroadcastRefinementEvidenceLedgerError(
      "INVALID_LEDGER",
      "The selected refinement lead plan is outside its bounded contract.",
    );
  }
  const rawLeadIds: readonly unknown[] = value.selectedLeadIds;
  const selectedLeadIds: string[] = [];
  const selected = new Set<string>();
  for (const leadId of rawLeadIds) {
    if (
      !isBoundedString(leadId, MAX_IDENTIFIER_LENGTH) ||
      selected.has(leadId)
    ) {
      throw new BroadcastRefinementEvidenceLedgerError(
        "INVALID_LEDGER",
        "Selected refinement lead IDs must be unique bounded strings.",
      );
    }
    selected.add(leadId);
    selectedLeadIds.push(leadId);
  }
  const rawSegments: readonly unknown[] = value.segments;
  const segmentIds = new Set<string>();
  const coveredLeadIds = new Set<string>();
  const segments = rawSegments.map((raw) => {
    if (
      !isRecord(raw) ||
      !hasExactKeys(raw, [
        "segmentId",
        "leadId",
        "sourceStartMs",
        "sourceEndMs",
      ]) ||
      !isBroadcastTranscriptChunkId(raw.segmentId) ||
      segmentIds.has(raw.segmentId) ||
      !isBoundedString(raw.leadId, MAX_IDENTIFIER_LENGTH) ||
      !selected.has(raw.leadId) ||
      !Number.isSafeInteger(raw.sourceStartMs) ||
      !Number.isSafeInteger(raw.sourceEndMs) ||
      (raw.sourceStartMs as number) < 0 ||
      (raw.sourceEndMs as number) <= (raw.sourceStartMs as number) ||
      (raw.sourceEndMs as number) > sourceDurationMs
    ) {
      throw new BroadcastRefinementEvidenceLedgerError(
        "INVALID_LEDGER",
        "Refinement segments must exactly reference the selected source-bounded leads.",
      );
    }
    segmentIds.add(raw.segmentId);
    coveredLeadIds.add(raw.leadId);
    return {
      segmentId: raw.segmentId,
      leadId: raw.leadId,
      sourceStartMs: raw.sourceStartMs as number,
      sourceEndMs: raw.sourceEndMs as number,
    };
  });
  if (
    selectedLeadIds.some((leadId) => !coveredLeadIds.has(leadId)) ||
    (selectedLeadIds.length === 0 && segments.length !== 0)
  ) {
    throw new BroadcastRefinementEvidenceLedgerError(
      "INVALID_LEDGER",
      "Every selected refinement lead requires at least one planned segment.",
    );
  }
  return {
    version: DISCOVERED_LEAD_REFINEMENT_VERSION,
    selectedLeadIds,
    segments,
    estimatedAsrCostUsd: value.estimatedAsrCostUsd,
  };
}

async function selectedLeadPlanFingerprint(
  sourceFingerprint: string,
  sourceDurationMs: number,
  plan: DiscoveredLeadRefinementPlan,
  digestAdapter: ContentDigestAdapter,
): Promise<string> {
  return createContentFingerprint(
    [
      SELECTED_LEAD_PLAN_FINGERPRINT_DOMAIN,
      sourceFingerprint,
      String(sourceDurationMs),
      JSON.stringify(plan),
    ],
    digestAdapter,
  );
}

function normalizedCaptionTrack(
  value: unknown,
  sourceDurationMs: number,
): YouTubeCaptionTrackResult {
  if (
    !isRecord(value) ||
    !hasExactKeys(value, [
      "videoId",
      "languageCode",
      "isAutoGenerated",
      "events",
    ]) ||
    typeof value.videoId !== "string" ||
    !YOUTUBE_VIDEO_ID_PATTERN.test(value.videoId) ||
    !isBoundedString(value.languageCode, 35) ||
    typeof value.isAutoGenerated !== "boolean" ||
    !Array.isArray(value.events) ||
    value.events.length === 0 ||
    value.events.length > MAX_YOUTUBE_CAPTION_EVENTS
  ) {
    throw new BroadcastRefinementEvidenceLedgerError(
      "INVALID_LEDGER",
      "The caption event source is invalid or unbounded.",
    );
  }
  const rawEvents: readonly unknown[] = value.events;
  let previousStartMs = -1;
  const events = rawEvents.map((raw) => {
    if (
      !isRecord(raw) ||
      !hasExactKeys(raw, ["startMs", "durationMs", "text"]) ||
      !Number.isSafeInteger(raw.startMs) ||
      !Number.isSafeInteger(raw.durationMs) ||
      (raw.startMs as number) < previousStartMs ||
      (raw.startMs as number) < 0 ||
      (raw.durationMs as number) < 0 ||
      (raw.startMs as number) > sourceDurationMs ||
      (raw.startMs as number) + (raw.durationMs as number) >
        sourceDurationMs ||
      !isBoundedString(raw.text, MAX_YOUTUBE_CAPTION_EVENT_TEXT_LENGTH)
    ) {
      throw new BroadcastRefinementEvidenceLedgerError(
        "INVALID_LEDGER",
        "Caption events must be chronological and source-bounded.",
      );
    }
    previousStartMs = raw.startMs as number;
    return {
      startMs: raw.startMs as number,
      durationMs: raw.durationMs as number,
      text: raw.text,
    };
  });
  return {
    videoId: value.videoId,
    languageCode: value.languageCode,
    isAutoGenerated: value.isAutoGenerated,
    events,
  };
}

function normalizedCaptionSpeechActivityEvidence(
  value: unknown,
  plan: DiscoveredLeadRefinementPlan,
  sourceDurationMs: number,
): readonly BroadcastRefinementCaptionSpeechActivityEvidence[] {
  if (!Array.isArray(value) || value.length > plan.segments.length) {
    throw new BroadcastRefinementEvidenceLedgerError(
      "INVALID_LEDGER",
      "Caption no-speech evidence cannot exceed the selected lead plan.",
    );
  }
  const segmentById = new Map(
    plan.segments.map((segment) => [segment.segmentId, segment] as const),
  );
  const planOrdinal = new Map(
    plan.segments.map((segment, ordinal) => [segment.segmentId, ordinal]),
  );
  const seenSegmentIds = new Set<string>();
  return (value as readonly unknown[])
    .map((raw): BroadcastRefinementCaptionSpeechActivityEvidence => {
      if (
        !isRecord(raw) ||
        !hasExactKeys(raw, ["segmentId", "receipt"]) ||
        !isBoundedString(raw.segmentId, MAX_IDENTIFIER_LENGTH) ||
        seenSegmentIds.has(raw.segmentId)
      ) {
        throw new BroadcastRefinementEvidenceLedgerError(
          "INVALID_LEDGER",
          "Caption no-speech evidence must name unique planned cells.",
        );
      }
      const segment = segmentById.get(raw.segmentId);
      const receipt = normalizeBroadcastSpeechActivityRunReceipt(raw.receipt);
      if (
        segment === undefined ||
        receipt === null ||
        receipt.sourceDurationMs !== sourceDurationMs ||
        receipt.sourceStartMs !== segment.sourceStartMs ||
        receipt.sourceEndMs !== segment.sourceEndMs ||
        !receipt.coverage.complete ||
        receipt.cells.length === 0 ||
        !receipt.cells.every(broadcastSpeechActivityCanSkipAsr)
      ) {
        throw new BroadcastRefinementEvidenceLedgerError(
          "INVALID_LEDGER",
          "Caption no-speech evidence is not a complete exact-range VAD receipt.",
        );
      }
      seenSegmentIds.add(raw.segmentId);
      return {
        segmentId: raw.segmentId,
        receipt,
      };
    })
    .sort(
      (left, right) =>
        (planOrdinal.get(left.segmentId) ?? Number.MAX_SAFE_INTEGER) -
        (planOrdinal.get(right.segmentId) ?? Number.MAX_SAFE_INTEGER),
    );
}

/**
 * Derives every caption cell outcome from fenced inputs. Caption text always
 * wins as exact success. A textless cell can be resolved as no-speech only by
 * a complete exact-range VAD receipt; otherwise it remains an explicit gap.
 */
export function createBroadcastRefinementCaptionCellSettlements(
  input: CreateBroadcastRefinementCaptionSettlementsInput,
): readonly BroadcastRefinementCaptionCellSettlement[] {
  const plan = normalizedSelectedLeadPlan(
    input.selectedLeadPlan,
    input.sourceDurationMs,
  );
  const track = normalizedCaptionTrack(
    input.captionTrack,
    input.sourceDurationMs,
  );
  const verifiedNoSpeechEvidence =
    normalizedCaptionSpeechActivityEvidence(
      input.verifiedNoSpeechEvidence,
      plan,
      input.sourceDurationMs,
    );
  const verifiedNoSpeechSegmentIds = new Set(
    verifiedNoSpeechEvidence.map(({ segmentId }) => segmentId),
  );
  const transcriptByRange = new Map(
    createYouTubeCaptionRefinementTranscripts(track, plan).map(
      (transcript) => [
        `${transcript.sourceStartMs}:${transcript.sourceEndMs}`,
        transcript.textKo,
      ],
    ),
  );
  return plan.segments.map((segment) => {
    const textKo = transcriptByRange.get(
      `${segment.sourceStartMs}:${segment.sourceEndMs}`,
    );
    if (textKo !== undefined) {
      return {
        ...segment,
        status: "success" as const,
        textKo,
      };
    }
    if (verifiedNoSpeechSegmentIds.has(segment.segmentId)) {
      return {
        ...segment,
        status: "resolved" as const,
        reason: "no-speech" as const,
      };
    }
    return {
      ...segment,
      status: "gap" as const,
      reason: "outcome-unknown" as const,
    };
  });
}

function normalizedCaptionSettlements(
  value: unknown,
  plan: DiscoveredLeadRefinementPlan,
  verifiedNoSpeechSegmentIds: ReadonlySet<string>,
): readonly BroadcastRefinementCaptionCellSettlement[] {
  if (
    !Array.isArray(value) ||
    value.length > plan.segments.length
  ) {
    throw new BroadcastRefinementEvidenceLedgerError(
      "INVALID_LEDGER",
      "Caption settlements cannot exceed the selected lead plan.",
    );
  }
  const rawSettlements: readonly unknown[] = value;
  const segmentById = new Map(
    plan.segments.map((segment) => [segment.segmentId, segment]),
  );
  const planOrdinal = new Map(
    plan.segments.map((segment, ordinal) => [segment.segmentId, ordinal]),
  );
  const settledIds = new Set<string>();
  const settlements = rawSettlements.map(
    (raw): BroadcastRefinementCaptionCellSettlement => {
      if (
        !isRecord(raw) ||
        !isBoundedString(raw.segmentId, MAX_IDENTIFIER_LENGTH) ||
        settledIds.has(raw.segmentId)
      ) {
        throw new BroadcastRefinementEvidenceLedgerError(
          "INVALID_LEDGER",
          "Caption settlements must name unique planned cells.",
        );
      }
      const planned = segmentById.get(raw.segmentId);
      const hasExactBase =
        planned !== undefined &&
        raw.leadId === planned.leadId &&
        raw.sourceStartMs === planned.sourceStartMs &&
        raw.sourceEndMs === planned.sourceEndMs;
      if (!hasExactBase || planned === undefined) {
        throw new BroadcastRefinementEvidenceLedgerError(
          "INVALID_LEDGER",
          "Caption evidence does not match its exact selected lead cell.",
        );
      }
      settledIds.add(raw.segmentId);
      const base: BroadcastRefinementEvidenceCellBase = {
        segmentId: planned.segmentId,
        leadId: planned.leadId,
        sourceStartMs: planned.sourceStartMs,
        sourceEndMs: planned.sourceEndMs,
      };
      if (
        raw.status === "success" &&
        hasExactKeys(raw, [
          "segmentId",
          "leadId",
          "sourceStartMs",
          "sourceEndMs",
          "status",
          "textKo",
        ]) &&
        isBoundedString(
          raw.textKo,
          MAX_BROADCAST_TRANSCRIPT_QWEN_TEXT_LENGTH,
        )
      ) {
        return { ...base, status: "success", textKo: raw.textKo };
      }
      if (
        raw.status === "resolved" &&
        hasExactKeys(raw, [
          "segmentId",
          "leadId",
          "sourceStartMs",
          "sourceEndMs",
          "status",
          "reason",
        ]) &&
        raw.reason === "no-speech" &&
        verifiedNoSpeechSegmentIds.has(planned.segmentId)
      ) {
        return { ...base, status: "resolved", reason: "no-speech" };
      }
      if (
        raw.status === "gap" &&
        hasExactKeys(raw, [
          "segmentId",
          "leadId",
          "sourceStartMs",
          "sourceEndMs",
          "status",
          "reason",
        ]) &&
        [
          "in-flight",
          "decode-failed",
          "transcription-failed",
          "rate-limited",
          "outcome-unknown",
        ].includes(typeof raw.reason === "string" ? raw.reason : "")
      ) {
        return {
          ...base,
          status: "gap",
          reason: raw.reason as BroadcastRefinementTranscriptGapReason,
        };
      }
      throw new BroadcastRefinementEvidenceLedgerError(
        "INVALID_LEDGER",
        "Caption settlement outcomes must be success, resolved, or an explicit gap.",
      );
    },
  );
  return settlements.sort(
    (left, right) =>
      (planOrdinal.get(left.segmentId) ?? Number.MAX_SAFE_INTEGER) -
      (planOrdinal.get(right.segmentId) ?? Number.MAX_SAFE_INTEGER),
  );
}

function settlementSummary(
  plannedCellCount: number,
  successCellCount: number,
  resolvedCellCount: number,
  gapCellCount: number,
): BroadcastRefinementEvidenceSettlementSummary {
  const accounted =
    successCellCount + resolvedCellCount + gapCellCount;
  const missingCellCount = plannedCellCount - accounted;
  if (
    !Number.isSafeInteger(plannedCellCount) ||
    [successCellCount, resolvedCellCount, gapCellCount, missingCellCount].some(
      (count) => !Number.isSafeInteger(count) || count < 0,
    )
  ) {
    throw new BroadcastRefinementEvidenceLedgerError(
      "INVALID_LEDGER",
      "Refinement evidence settlement counts are inconsistent.",
    );
  }
  const settled = gapCellCount === 0 && missingCellCount === 0;
  return {
    plannedCellCount,
    successCellCount,
    resolvedCellCount,
    gapCellCount,
    missingCellCount,
    status: settled ? "settled" : "blocked",
    publicationEligible: settled,
  };
}

function canonicalRefinementCheckpoint(
  value: BroadcastRefinementTranscriptCheckpoint,
): BroadcastRefinementTranscriptCheckpoint {
  const serialized = serializeBroadcastRefinementTranscriptCheckpoint(value);
  const parsed = parseBroadcastRefinementTranscriptCheckpointJson(serialized);
  if (parsed === null) {
    throw new BroadcastRefinementEvidenceLedgerError(
      "INVALID_LEDGER",
      "The ASR refinement checkpoint is not canonical.",
    );
  }
  return parsed;
}

function canonicalProviderCheckpoint(
  value: BroadcastTranscriptProviderReceiptCheckpoint,
): BroadcastTranscriptProviderReceiptCheckpoint {
  const serialized =
    serializeBroadcastTranscriptProviderReceiptCheckpoint(value);
  const parsed =
    parseBroadcastTranscriptProviderReceiptCheckpointJson(serialized);
  if (parsed === null) {
    throw new BroadcastRefinementEvidenceLedgerError(
      "INVALID_LEDGER",
      "The ASR provider receipt checkpoint is not canonical.",
    );
  }
  return parsed;
}

function expectedAsrChunks(plan: DiscoveredLeadRefinementPlan) {
  return [...plan.segments]
    .map((segment) => ({
      chunkId: segment.segmentId,
      sourceStartMs: segment.sourceStartMs,
      sourceEndMs: segment.sourceEndMs,
      kind: "event" as const,
    }))
    .sort(
      (left, right) =>
        left.sourceStartMs - right.sourceStartMs ||
        left.sourceEndMs - right.sourceEndMs ||
        left.chunkId.localeCompare(right.chunkId),
    );
}

function validatedAsrPayload(
  refinementCheckpointValue: BroadcastRefinementTranscriptCheckpoint,
  providerCheckpointValue: BroadcastTranscriptProviderReceiptCheckpoint,
  plan: DiscoveredLeadRefinementPlan,
  sourceFingerprint: string,
  sourceDurationMs: number,
): {
  readonly payload: BroadcastRefinementAsrEvidencePayload;
  readonly evidenceRevision: string;
  readonly settlement: BroadcastRefinementEvidenceSettlementSummary;
} {
  const refinementCheckpoint = canonicalRefinementCheckpoint(
    refinementCheckpointValue,
  );
  const providerReceiptCheckpoint = canonicalProviderCheckpoint(
    providerCheckpointValue,
  );
  const expectedChunks = expectedAsrChunks(plan);
  const expectedProviderCells = expectedChunks.map(
    ({ chunkId, sourceStartMs, sourceEndMs }) => ({
      chunkId,
      sourceStartMs,
      sourceEndMs,
    }),
  );
  if (
    JSON.stringify(refinementCheckpoint.plannedChunks) !==
      JSON.stringify(expectedChunks) ||
    JSON.stringify(providerReceiptCheckpoint.plannedCells) !==
      JSON.stringify(expectedProviderCells) ||
    providerReceiptCheckpoint.sourceFingerprint !== sourceFingerprint ||
    providerReceiptCheckpoint.sourceDurationMs !== sourceDurationMs
  ) {
    throw new BroadcastRefinementEvidenceLedgerError(
      "STALE_BINDING",
      "ASR checkpoints do not match the current source and selected lead plan.",
    );
  }
  const receiptByChunkId = new Map(
    providerReceiptCheckpoint.receipts.map((entry) => [
      entry.chunkId,
      entry,
    ]),
  );
  if (
    receiptByChunkId.size !==
    refinementCheckpoint.successfulFragments.length
  ) {
    throw new BroadcastRefinementEvidenceLedgerError(
      "INVALID_LEDGER",
      "Every successful ASR cell requires one exact provider receipt.",
    );
  }
  for (const fragment of refinementCheckpoint.successfulFragments) {
    const providerEntry = receiptByChunkId.get(fragment.chunkId);
    if (
      providerEntry === undefined ||
      providerEntry.sourceStartMs !== fragment.result.sourceStartMs ||
      providerEntry.sourceEndMs !== fragment.result.sourceEndMs ||
      JSON.stringify(providerEntry.receipt) !==
        JSON.stringify(fragment.result.providerReceipt)
    ) {
      throw new BroadcastRefinementEvidenceLedgerError(
        "INVALID_LEDGER",
        "ASR evidence and its provider receipt checkpoint disagree.",
      );
    }
  }
  for (const abstention of refinementCheckpoint.abstentions) {
    if (
      abstention.reason === "no-speech" &&
      (abstention.speechActivityReceipt === null ||
        abstention.speechActivityReceipt.sourceDurationMs !==
          sourceDurationMs)
    ) {
      throw new BroadcastRefinementEvidenceLedgerError(
        "INVALID_LEDGER",
        "ASR no-speech evidence requires one exact source-bound VAD receipt.",
      );
    }
  }
  const settlement = settlementSummary(
    expectedChunks.length,
    refinementCheckpoint.successfulFragments.length,
    refinementCheckpoint.abstentions.length,
    refinementCheckpoint.gaps.length,
  );
  if (
    settlement.publicationEligible !==
    broadcastRefinementTranscriptCheckpointCanComplete(
      refinementCheckpoint,
    )
  ) {
    throw new BroadcastRefinementEvidenceLedgerError(
      "INVALID_LEDGER",
      "ASR settlement disagrees with its refinement checkpoint.",
    );
  }
  return {
    payload: {
      kind: "asr-refinement-checkpoints",
      refinementCheckpoint,
      providerReceiptCheckpoint,
    },
    evidenceRevision:
      broadcastTranscriptProviderReceiptCheckpointModelRevision(
        providerReceiptCheckpoint,
      ),
    settlement,
  };
}

